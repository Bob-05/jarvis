"""Мелкие утилиты общего назначения."""
import re
from datetime import datetime


def detect_language(text: str) -> str:
    """Возвращает 'ru', если есть кириллица, иначе 'en'."""
    cyrillic = sum(1 for ch in text if "\u0400" <= ch <= "\u04FF")
    return "ru" if cyrillic > 0 else "en"


def strip_cjk(text: str) -> str:
    """Убирает CJK-иероглифы и полноширинные символы."""
    return re.sub(
        r"[\u3000-\u303f\u3040-\u30ff\u3400-\u4dbf\u4e00-\u9fff\uff00-\uffef]+",
        "", text,
    ).strip()


def build_datetime_context() -> str:
    """Строка с актуальной датой/временем для системного промпта."""
    now = datetime.now()
    days = ["понедельник", "вторник", "среда", "четверг",
            "пятница", "суббота", "воскресенье"]
    months = ["января", "февраля", "марта", "апреля", "мая", "июня",
              "июля", "августа", "сентября", "октября", "ноября", "декабря"]
    return (
        f"АКТУАЛЬНЫЕ ДАННЫЕ: Сегодня {now.day} {months[now.month - 1]} {now.year} года, "
        f"{days[now.weekday()]}. Текущее время: {now.strftime('%H:%M')}. "
        f"Используй ТОЛЬКО эту дату как «сегодня». Если пользователь спрашивает "
        f"о свежих событиях, новостях, курсах, погоде — ОБЯЗАТЕЛЬНО вызывай [ПОИСК], "
        f"не выдумывай. Никогда не говори старые даты."
    )